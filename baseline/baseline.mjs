// Administrator-controlled baseline (isolated CLI). Same six synthetic fixtures, same scenarios as the app's checks (S1–S9 in docs/VERIFICATION.md).
// No imports from src/, no server, no network. Exists only to show what the protected design changes.
import { createCipheriv, createDecipheriv, randomBytes } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
// Load the fixture texts by parsing the TS source as data (no shared code path with the app).
const src = readFileSync(join(here, "..", "src", "lib", "fixtures.ts"), "utf8");
const block = src.slice(src.indexOf("export const FIXTURES"), src.indexOf("];", src.indexOf("export const FIXTURES")) + 1);
const FIXTURES = Function(`"use strict"; return (${block.slice(block.indexOf("["))});`)();

const serverKey = randomBytes(32); // the single key the operator holds
const enc = (t) => { const iv = randomBytes(12); const c = createCipheriv("aes-256-gcm", serverKey, iv); const ct = Buffer.concat([c.update(t, "utf8"), c.final()]); return { iv, ct, tag: c.getAuthTag() }; };
const dec = (r) => { const d = createDecipheriv("aes-256-gcm", serverKey, r.iv); d.setAuthTag(r.tag); return Buffer.concat([d.update(r.ct), d.final()]).toString("utf8"); };

const db = { contributions: new Map(), permissions: new Set(), audit: [] };
FIXTURES.forEach((f) => db.contributions.set(f.id, { owner: "participant", ...enc(f.text), language: f.language }));
const perm = (c, u) => `${c}::${u}`;
const read = (user, cid) => { const c = db.contributions.get(cid); if (!c) return { ok: false, why: "not_found" }; if (user !== c.owner && !db.permissions.has(perm(cid, user))) return { ok: false, why: "no_permission" }; return { ok: true, text: dec(c) }; };
const adminSetPermission = (admin, cid, user) => { db.permissions.add(perm(cid, user)); db.audit.push({ admin, cid, user, approvals: 1 }); return true; }; // one admin, no quorum

const rows = [];
const rec = (id, scenario, expectProtected, observed, baselineResult) => rows.push({ id, scenario, expectProtected, observed, baselineResult });
const C1 = "fx-vi-1", C2 = "fx-en-2";

// S1 owner shares C1 with A
db.permissions.add(perm(C1, "researcher_a"));
let r = read("researcher_a", C1); rec("S1", "Owner-approved grant lets A open C1", "A can read", r.ok ? "A read the text" : "A refused", r.ok ? "PASS" : "FAIL");
r = read("researcher_b", C1); rec("S2a", "B requests C1", "refused", r.ok ? "B READ IT" : `refused (${r.why})`, r.ok ? "FAIL" : "PASS");
r = read("researcher_a", C2); rec("S2b", "A requests unshared C2 (changed id)", "refused", r.ok ? "A READ IT" : `refused (${r.why})`, r.ok ? "FAIL" : "PASS");
// S2c: B is handed the stored record directly (DB leak) — in the baseline the record is opened by the server key
const leaked = db.contributions.get(C1); let leakOpened = false; try { leakOpened = !!dec(leaked); } catch {}
rec("S2c", "Stored record leaked (DB + server key, e.g. operator)", "no plaintext", leakOpened ? "plaintext recovered with the server key" : "no plaintext", leakOpened ? "FAIL" : "PASS");
// S3 withdrawal
db.permissions.delete(perm(C1, "researcher_a")); r = read("researcher_a", C1); rec("S3", "After withdrawal A requests C1", "refused", r.ok ? "A READ IT" : `refused (${r.why})`, r.ok ? "FAIL" : "PASS");
// S4 one admin grants themselves access
adminSetPermission("admin", C2, "admin"); r = read("admin", C2); rec("S4", "One admin grants themselves C2", "no effective access", r.ok ? "admin read the text with ONE approval" : "refused", r.ok ? "FAIL" : "PASS");
// S5 quorum
rec("S5", "Change needs 2 distinct approvals; duplicate doesn't count", "threshold enforced", `applied with ${db.audit.at(-1).approvals} approval (no quorum concept)`, "FAIL");
// S6 master/bootstrap path: the operator holds the server key
rec("S6", "Operator/bootstrap path reads content", "no plaintext", "server key decrypts every contribution", "FAIL");
// S9 metadata change without owner consent
db.permissions.add(perm(C1, "researcher_b")); r = read("researcher_b", C1); rec("S9", "Admin edits permission row for B on C1, no owner consent", "B gets no plaintext", r.ok ? "B read the text" : "refused", r.ok ? "FAIL" : "PASS");
// S8 text integrity on all six fixtures
const intact = FIXTURES.every((f) => dec(db.contributions.get(f.id)) === f.text); rec("S8", "Six fixtures round-trip without text change", "unchanged", intact ? "all 6 identical (Unicode preserved)" : "CHANGED", intact ? "PASS" : "FAIL");

serverKey.fill(0);
const fails = rows.filter((x) => x.baselineResult === "FAIL").length;
const md = [
  "# Baseline results (administrator-controlled portal)",
  "",
  `Generated by \`npm run baseline\` at ${new Date().toISOString()}. Isolated CLI; same six synthetic fixtures. ` +
    `FAIL means the baseline does NOT provide that protection, which is the point of the comparison.`,
  "",
  "| Test | Scenario | Required | Observed in baseline | Baseline |",
  "|---|---|---|---|---|",
  ...rows.map((x) => `| ${x.id} | ${x.scenario} | ${x.expectProtected} | ${x.observed} | ${x.baselineResult} |`),
  "",
  `Baseline fails ${fails} of ${rows.length} checks.`,
  "",
].join("\n");
mkdirSync(join(here, "..", "evidence"), { recursive: true });
writeFileSync(join(here, "..", "evidence", "baseline-results.md"), md);
console.log(md);
